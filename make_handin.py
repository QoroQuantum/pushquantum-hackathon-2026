"""Collect the best verified solution per portfolio instance into handin/ and write the table.

Every candidate .sol under the given result folders (and the current handin/) is
re-scored with the official referee (``qoblib_tools.PortfolioModel.score``). Per
instance the best feasible one is copied to ``handin/<instance>_b<B>_l<λ>.sol`` (only
if it beats the file already there), and ``handin/RESULTS.md`` lists every hand-in file
with its gap to QOBLIB's best-known value. ``submission/<stem>.json`` gets the qubit
count and method line for the Aqora upload (``submission/upload.py``).

    python make_handin.py --dirs results/grid results/grid_polish results/day_swap
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

import qoblib_tools as qt
from grid_runs import lam_tag, load_bkv

HANDIN = Path("handin")


def n_binary(model) -> int:
    """Official QUBO size: (6 bits per asset + cash slack + count slack) per period."""
    return (6 * len(model.symbols) + model.cash_slack_bits + model.count_slack_bits) * model.n_periods


def comment(path: Path) -> str:
    for line in path.read_text().splitlines():
        if line.startswith("#") and "period symbol" not in line:
            return line.lstrip("# ").strip()
    return ""


_models = {}


def score(path: Path):
    h, pos = qt.read_portfolio_solution(path)
    key = (h["instance"], int(h["budget"]), lam_tag(h["lambda"]))
    if key not in _models:
        _models[key] = qt.PortfolioModel(qt.load_portfolio_instance(h["instance"]), budget=key[1], lam=h["lambda"])
    m = _models[key]
    sc = m.score(pos)
    return f"{key[0]}_b{key[1]:03d}_l{key[2]}", m, sc


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dirs", nargs="+", default=["results/grid", "results/grid_polish"])
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--prefer", nargs="*", default=["results/exact_dp"],
                    help="folders whose files win ties (e.g. proven-optimal DP solutions)")
    ap.add_argument("--quantum", default="{}",
                    help='JSON {stem: [qubits, method]} for files a quantum program contributed to')
    a = ap.parse_args()
    quantum = json.loads(a.quantum)
    pref = [Path(d).resolve() for d in a.prefer]
    preferred = lambda p: any(d in Path(p).resolve().parents for d in pref)  # noqa: E731
    bkv = load_bkv()
    best = {}
    for d in [HANDIN, *map(Path, a.dirs)]:
        for p in sorted(d.rglob("*.sol")):
            if p.name.endswith(".ckpt.sol"):
                continue
            try:
                key, m, sc = score(p)
            except Exception as e:  # noqa: BLE001 - skip unreadable files, but say so
                print(f"skip {p}: {e}")
                continue
            if not sc.feasible:
                continue
            cur = best.get(key)
            # prefer the current hand-in file on ties, so its method line stays
            if cur is None or sc.objective < cur[0] or (sc.objective == cur[0] and preferred(p)
                                                         and not preferred(cur[1])):
                best[key] = (int(sc.objective), p, m)
    changed = []
    for key, (obj, p, m) in sorted(best.items()):
        dest = HANDIN / f"{key}.sol"
        if p.resolve() == dest.resolve() or (dest.exists() and dest.read_bytes() == p.read_bytes()):
            continue
        if dest.exists():
            _, _, old = score(dest)
            if old.feasible and (old.objective < obj or (old.objective == obj and not preferred(p))):
                continue
        changed.append((key, obj, p))
        if not a.dry_run:
            shutil.copyfile(p, dest)
    print(f"{len(changed)} hand-in files new or improved")
    for key, obj, p in changed:
        print(f"  {key}: {obj}  <- {p}")
    if a.dry_run:
        return

    # table
    rows = []
    for p in sorted(HANDIN.glob("*.sol")):
        key, m, sc = score(p)
        assert sc.feasible, p
        bk = bkv.get(key)
        gap = None if bk is None else (sc.objective - bk) / abs(bk) * 100
        rows.append(dict(file=p.name, key=key, assets=len(m.symbols), periods=m.n_periods, vars=n_binary(m),
                         score=int(sc.objective), bkv=bk, gap=gap, method=comment(p)))
    order = lambda r: (-r["vars"], r["key"].split("_")[3], -float(r["key"].rsplit("_l", 1)[1] or 0))  # noqa: E731
    rows.sort(key=order)
    with_bkv = [r for r in rows if r["gap"] is not None]
    beat = [r for r in with_bkv if r["gap"] < -1e-9]
    match = [r for r in with_bkv if abs(r["gap"]) <= 1e-9]
    worse = [r for r in with_bkv if r["gap"] > 1e-9]
    lines = [
        "# Hand-in results (generated by `make_handin.py`)",
        "",
        f"{len(rows)} solution files, all feasible under the official referee (`qoblib_tools.py`). "
        f"{len(with_bkv)} of the instances have a QOBLIB best-known value (BKV): "
        f"**{len(beat)} beat it, {len(match)} match it, {len(worse)} {'is' if len(worse) == 1 else 'are'} above it** "
        f"(largest gap {max((r['gap'] for r in worse), default=0):.3f}%). "
        f"Negative gaps beat the BKV. Binary variables = the official QUBO size, "
        f"`(6n + 4 cash-slack + 7 count-slack bits) x T`.",
        "",
        "| file | assets x days | binary vars | score | best known | gap | how it was found |",
        "|---|---|---:|---:|---:|---:|---|",
    ]
    for r in rows:
        g = "—" if r["gap"] is None else (f"**{r['gap']:+.2f}%**" if r["gap"] < -1e-9 else f"{r['gap']:+.2f}%")
        bk = "—" if r["bkv"] is None else f"{r['bkv']:.0f}"
        lines.append(f"| `{r['file']}` | {r['assets']} x {r['periods']} | {r['vars']:,} | {r['score']} | {bk} | {g} "
                     f"| {r['method']} |")
    (HANDIN / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {HANDIN / 'RESULTS.md'}: {len(rows)} files, {len(beat)} beat / {len(match)} match / "
          f"{len(worse)} above BKV")

    # Aqora upload folder: .sol + .json per instance. Entries already there (some come from
    # teammates' runs, with their own method line) are replaced only by a better solution.
    sub = Path("submission")
    sub.mkdir(exist_ok=True)
    n_sub = 0
    for r in rows:
        stem = r["file"][:-4]
        ssol, sjson = sub / f"{stem}.sol", sub / f"{stem}.json"
        if ssol.exists() and sjson.exists() and stem not in quantum:
            _, _, old = score(ssol)
            if old.feasible and old.objective <= r["score"]:
                continue
        q, meth = quantum.get(stem, (0, r["method"] or "classical"))
        shutil.copyfile(HANDIN / r["file"], ssol)
        sjson.write_text(json.dumps({"qubits": q, "method": meth}))
        n_sub += 1
    print(f"submission/: {n_sub} entries written or updated")


if __name__ == "__main__":
    main()
